// pnpm assets:synthetic-demo — cloud-safe end-to-end run of the fan-local pipeline on SYNTHETIC
// sources (code-drawn shapes, no RO material): sources + lock + extraction under
// .local-assets/synthetic-demo/ (git-ignored), and marker-free copies of the contact sheets and
// walk grid in reports/phase1/synthetic/ as pipeline evidence.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { AssetWhitelist } from "@ro-survivor/asset-contracts";
import { createAssetReader } from "@ro-survivor/asset-gateway";
import { decodeOwnPng, encodePng } from "../lib/png.ts";
import { auditWhitelist } from "./audit-whitelist-lib.ts";
import { runExtraction } from "./extract-run.ts";
import { repoRoot } from "./local-context.ts";
import { CANONICAL_WHITELIST_SHA256 } from "@ro-survivor/asset-contracts";
/** Verified lock of the reader + canonical v3 whitelist hash (synthetic run). */
const identityOf = (r: { lockId: string }) => ({ lockId: r.lockId, whitelistSha256: CANONICAL_WHITELIST_SHA256 });
import { buildSyntheticSources } from "./synthetic-sources.ts";

const base = join(repoRoot, ".local-assets/synthetic-demo");
rmSync(base, { recursive: true, force: true });
const realRows = AssetWhitelist.fromCsv(readFileSync(join(repoRoot, "docs/product-plan/handoff/fan-local-asset-whitelist.csv"), "utf8")).rows();
const src = buildSyntheticSources(join(base, "src"), realRows);
writeFileSync(join(base, "source-lock.json"), JSON.stringify(src.lock, null, 2));
const reader = createAssetReader(src.lock);
try {
  const audit = auditWhitelist(src.rows, reader);
  console.log(`audit (synthetic): ${audit.filter((r) => r.status === "PASS").length}/${audit.length} PASS`);
  const derived = join(base, "derived");
  const m = runExtraction(src.rows, reader, derived, { identity: identityOf(reader) });
  console.log(`extract (synthetic): ${m.outputs.length} outputs, ${m.sprites.length} actors, map reachable ${m.map?.flood.reachableFromSpawn}/${m.map?.flood.walkable}`);
  const evidence = join(repoRoot, "reports/phase1/synthetic");
  mkdirSync(evidence, { recursive: true });
  for (const [from, to] of [
    [join(derived, "contact-sheets/player.swordsman.male.png"), "synthetic-contact-sheet-player.png"],
    [join(derived, "contact-sheets/monster.1002.png"), "synthetic-contact-sheet-monster.png"],
    [join(derived, "map.prt_fild08.gat.png"), "synthetic-walk-grid.png"],
  ] as const) {
    const img = decodeOwnPng(readFileSync(from));
    writeFileSync(join(evidence, to), encodePng(img.width, img.height, img.rgba));
  }
  writeFileSync(join(evidence, "synthetic-extract-summary.json"), JSON.stringify({ note: "SYNTHETIC sources generated by code; not RO material", audit: { pass: audit.filter((r) => r.status === "PASS").length, total: audit.length }, sprites: m.sprites, map: m.map }, null, 2) + "\n");
  console.log(`gateway for the demo: RO_GATEWAY_LOCK_FILE=${join(".local-assets/synthetic-demo/source-lock.json")} RO_GATEWAY_DERIVED_DIR=.local-assets/synthetic-demo/derived pnpm gateway`);
} finally {
  reader.close();
}
