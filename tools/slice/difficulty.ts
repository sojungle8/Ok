// pnpm slice:difficulty — hard difficulty and Base-level progression gate for every job (headless).
// For each build: normal (Base 0), hard (Base 0) and hard (Base 10) over 10 fixed seeds. Gates: hard
// is never easier than normal, and with Base level 10 every build of every job wins >= 5/10 on hard.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { applyRunModifiers, MAGE_PLANS, SWORDSMAN_PLANS, type BuildPlan, type RunContent } from "@ro-survivor/core-sim";
import { mageContent, playJobRun, sliceContent } from "./slice-fixture.ts";

const root = resolve(import.meta.dirname, "../..");
const checkOnly = process.argv.includes("--check");
const seeds = Array.from({ length: 10 }, (_, i) => i + 1);
const jobs: { job: string; content: RunContent; plans: readonly BuildPlan[] }[] = [
  { job: "swordsman", content: sliceContent, plans: SWORDSMAN_PLANS },
  { job: "mage", content: mageContent, plans: MAGE_PLANS },
];
const modes = [{ id: "normal-bl0", difficulty: "normal", baseLevel: 0 }, { id: "hard-bl0", difficulty: "hard", baseLevel: 0 }, { id: "hard-bl10", difficulty: "hard", baseLevel: 10 }] as const;
const rows: { job: string; plan: string; mode: string; wins: number; outcomes: string[] }[] = [];
for (const j of jobs) {
  for (const mode of modes) {
    const content = applyRunModifiers(j.content, { difficulty: mode.difficulty, baseLevel: mode.baseLevel });
    for (const plan of j.plans) {
      const outcomes = seeds.map((s) => playJobRun(content, s, plan).phase);
      rows.push({ job: j.job, plan, mode: mode.id, wins: outcomes.filter((o) => o === "victory").length, outcomes });
    }
  }
}
const wins = (job: string, plan: string, mode: string): number => rows.find((r) => r.job === job && r.plan === plan && r.mode === mode)?.wins ?? 0;
const all = (test: (job: string, plan: string) => boolean): boolean => jobs.every((j) => j.plans.every((p) => test(j.job, p)));
const gates = {
  "hard is never easier than normal (per build)": all((j, p) => wins(j, p, "hard-bl0") <= wins(j, p, "normal-bl0")),
  "hard + Base 10: every build of every job wins >= 5/10": all((j, p) => wins(j, p, "hard-bl10") >= 5),
  "Base 10 never lowers hard wins (per build)": all((j, p) => wins(j, p, "hard-bl10") >= wins(j, p, "hard-bl0")),
};
const digest = createHash("sha256").update(JSON.stringify(rows)).digest("hex").toUpperCase();
const jsonPath = join(root, "reports/phase2/difficulty-progression.json");
let stale = false;
if (checkOnly) {
  try {
    stale = (JSON.parse(readFileSync(jsonPath, "utf8")) as { rowsSha256?: string }).rowsSha256 !== digest;
  } catch {
    stale = true;
  }
} else {
  writeFileSync(jsonPath, JSON.stringify({ generator: "tools/slice/difficulty.ts", seeds, modes, rowsSha256: digest, gates, rows }, null, 2) + "\n");
  writeFileSync(join(root, "reports/phase2/difficulty-progression.md"), `# Hard difficulty and Base-level progression (automated)

Generated by \`pnpm slice:difficulty\` (headless, deterministic, **no assets**; analog bot, 10 fixed seeds). Hard and Base
level are content transforms applied before the run; normal Base-0 runs are byte-identical to the slice. Rows digest \`${digest}\`.

| Job | Build | normal (Base 0) | hard (Base 0) | hard (Base 10) |
| --- | --- | --- | --- | --- |
${jobs.flatMap((j) => j.plans.map((p) => `| ${j.job} | ${p} | ${wins(j.job, p, "normal-bl0")}/10 | ${wins(j.job, p, "hard-bl0")}/10 | ${wins(j.job, p, "hard-bl10")}/10 |`)).join("\n")}

## Gates

| Gate | Result |
| --- | --- |
${Object.entries(gates).map(([k, v]) => `| ${k} | ${v ? "PASS" : "FAIL"} |`).join("\n")}
`);
}
console.log(JSON.stringify({ gates, rowsSha256: digest, stale }, null, 1));
if (!Object.values(gates).every(Boolean) || stale) process.exitCode = 1;
