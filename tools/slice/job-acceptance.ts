// pnpm slice:job-acceptance -- --job=mage — headless acceptance for an additional job pack on the same
// stage: 3 build plans × keyboard/touch/gamepad × 10 fixed seeds. Gates mirror the Swordsman slice:
// no crash, every build ≥ 7/10 wins per device, effective area clear (≥ 3 non-MVP targets) within
// 60 s in every run, no unannounced hits. `--check` recomputes and fails on stale or failing reports.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { MAGE_PLANS, type BuildPlan } from "@ro-survivor/core-sim";
import { acceptanceRun, type RunRow } from "./acceptance-lib.ts";
import { mageContent } from "./slice-fixture.ts";

const root = resolve(import.meta.dirname, "../..");
const checkOnly = process.argv.includes("--check");
const plans: readonly BuildPlan[] = MAGE_PLANS;
const devices = ["keyboard", "touch", "gamepad"] as const;
const seeds = Array.from({ length: 10 }, (_, i) => i + 1);
const rows: RunRow[] = [];
for (const plan of plans) for (const device of devices) for (const seed of seeds) rows.push(acceptanceRun(seed, plan, device, mageContent));
const wins = (p: string, d: string): number => rows.filter((r) => r.plan === p && r.device === d && r.outcome === "victory").length;
const matrix = plans.map((p) => ({ plan: p, ...Object.fromEntries(devices.map((d) => [d, wins(p, d)])) }));
const areaClear = rows.map((r) => r.firstEffectiveAreaClearTick);
const gates = {
  "no crash": rows.every((r) => r.crashed === null),
  "every build >= 7/10 wins on every device": plans.every((p) => devices.every((d) => wins(p, d) >= 7)),
  "effective area clear within 60 s in every run": areaClear.every((t) => t >= 0 && t <= 60 * 60),
  "no unannounced hits": rows.every((r) => r.unannouncedHits === 0),
  "skills never move the player": rows.every((r) => r.playerMovedBySkills === 0),
};
const digest = createHash("sha256").update(JSON.stringify(rows)).digest("hex").toUpperCase();
const jsonPath = join(root, "reports/phase2/job-acceptance-mage.json");
let stale = false;
if (checkOnly) {
  try {
    stale = (JSON.parse(readFileSync(jsonPath, "utf8")) as { rowsSha256?: string }).rowsSha256 !== digest;
  } catch {
    stale = true;
  }
} else {
  const sorted = [...areaClear].sort((a, b) => a - b);
  const report = {
    generator: "tools/slice/job-acceptance.ts", job: "mage", contentVersion: mageContent.contentVersion, seeds, devices, plans,
    rowsSha256: digest, gates, matrix,
    areaClearSeconds: { p50: Math.round((sorted[Math.floor(sorted.length / 2)] ?? 0) / 6) / 10, max: Math.round((sorted.at(-1) ?? 0) / 6) / 10 },
    rows: rows.map((r) => ({ plan: r.plan, device: r.device, seed: r.seed, outcome: r.outcome, timeSeconds: r.timeSeconds, level: r.level, kills: r.kills, areaClearTick: r.firstEffectiveAreaClearTick, keystone: r.keystone, topDamageSource: r.topDamageSource })),
  };
  writeFileSync(jsonPath, JSON.stringify(report, null, 2) + "\n");
  writeFileSync(join(root, "reports/phase2/job-acceptance-mage.md"), `# Mage job acceptance (automated)

Generated by \`pnpm slice:job-acceptance -- --job=mage\` (headless, deterministic, **no assets**). Content \`${mageContent.contentVersion}\`,
same signed stage/monsters/progression as the Swordsman slice. Bots stand in for players; human play is DEFERRED_LOCAL.
Rows digest: \`${digest}\`.

## Wins per device (of 10 seeds)

| Build | keyboard | touch | gamepad |
| --- | --- | --- | --- |
${matrix.map((m) => `| ${m.plan} | ${devices.map((d) => String((m as Record<string, unknown>)[d])).join(" | ")} |`).join("\n")}

Effective area clear: p50 ${report.areaClearSeconds.p50} s, max ${report.areaClearSeconds.max} s.

## Gates

| Gate | Result |
| --- | --- |
${Object.entries(gates).map(([k, v]) => `| ${k} | ${v ? "PASS" : "FAIL"} |`).join("\n")}
`);
}
console.log(JSON.stringify({ gates, matrix, rowsSha256: digest, stale }, null, 1));
if (!Object.values(gates).every(Boolean) || stale) process.exitCode = 1;
