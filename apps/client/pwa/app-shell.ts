/**
 * Offline app shell (Phase 3.3). The service worker precaches only the built HTML/JS/CSS of this
 * client. It never caches RO data: requests outside the precached shell (gateway, GRF, derived files,
 * local assets) pass straight to the network. A new version is installed in the background and takes
 * over at the next launch; the running game is never reloaded mid-run.
 */
const SHELL_EXT = /\.(?:html|js|css|webmanifest)$/u;
const FORBIDDEN = /(?:^|\/)(?:\.local-assets|data|bgm|system)(?:\/|$)|\.(?:grf|spr|act|gnd|gat|rsw|rsm|str|bmp|tga|wav|mp3|png|jpe?g)$/iu;

/** Files from the build output that belong to the precached shell (deterministic order). */
export function shellFiles(fileNames: readonly string[]): string[] {
  const files = fileNames.filter((f) => SHELL_EXT.test(f) && !FORBIDDEN.test(f) && f !== "sw.js");
  if (files.some((f) => f.includes(".."))) throw new Error("shell file outside the build output");
  return [...new Set(files)].sort();
}

