/** Source of sw.js for one build. `files` are relative to the service worker scope. */
export function serviceWorkerSource(buildId: string, files: readonly string[]): string {
  const cache = `ro-survivor-shell-${buildId.replace(/[^A-Za-z0-9._+-]/gu, "_")}`;
  const shell = ["./", ...files.map((f) => `./${f}`)];
  return `// Generated by apps/client/pwa/app-shell.ts — app shell only, never RO data.
const CACHE = ${JSON.stringify(cache)};
const SHELL = ${JSON.stringify(shell)};
const SHELL_PATHS = new Set(SHELL.map((p) => new URL(p, self.registration.scope).pathname));
self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)));
});
self.addEventListener("activate", (event) => {
  event.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("ro-survivor-shell-") && k !== CACHE).map((k) => caches.delete(k)))));
});
self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || !SHELL_PATHS.has(url.pathname)) return;
  event.respondWith(caches.open(CACHE).then((c) => c.match(req, { ignoreSearch: true }).then((hit) => hit ?? fetch(req))));
});
`;
}
