import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { request } from "node:http";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import {
  AssetWhitelist, connectAssetGateway, encodeCp949, GatewayError, hexToBytes, HttpAssetGatewayClient, isPlaceholderBinary, UnknownAssetError, bytesToHex,
} from "@ro-survivor/asset-contracts";
import type { SourceLockLocal, WhitelistRow } from "@ro-survivor/content-schema";
import { createTempDir, syntheticBytes, writeGrf } from "@ro-survivor/testkit";
import { startGateway, type RunningGateway } from "../src/index.ts";

const sha = (b: Uint8Array) => createHash("sha256").update(b).digest("hex").toUpperCase();
const cleanups: (() => Promise<void> | void)[] = [];
afterEach(async () => {
  while (cleanups.length) await cleanups.pop()?.();
});

function row(p: Partial<WhitelistRow> & Pick<WhitelistRow, "asset_id" | "canonical_cp949_path" | "bytes">): WhitelistRow {
  const raw = p.source_container === "filesystem:BGM" ? "" : bytesToHex(encodeCp949(p.canonical_cp949_path));
  return {
    category: "test", source_container: "data.grf", normalized_request_path: "/x", raw_name_hex: raw, sha256: "",
    source_id: "", source_key: "", act_version: "", act_actions: "", required: "true", rdata_override: "false", notes: "", ...p,
  };
}

/** Synthetic sources: a GRF holding generated bytes under whitelisted CP949 names, and a BGM dir. */
async function fixture(): Promise<{ gw: RunningGateway; whitelist: AssetWhitelist; data: Record<string, Uint8Array>; lock: SourceLockLocal }> {
  const d = createTempDir("gateway-");
  cleanups.push(() => d.dispose());
  const poring = syntheticBytes(1, 4321);
  const gat = syntheticBytes(2, 777);
  const wrong = syntheticBytes(3, 50);
  const bgm = syntheticBytes(4, 900);
  const rows = [
    row({ asset_id: "monster.1002.spr", canonical_cp949_path: "data\\sprite\\몬스터\\poring.spr", bytes: poring.length }),
    row({ asset_id: "map.prt_fild08.gat", canonical_cp949_path: "data\\prt_fild08.gat", bytes: gat.length, sha256: sha(gat).toLowerCase() }),
    row({ asset_id: "map.prt_fild08.gnd", canonical_cp949_path: "data\\prt_fild08.gnd", bytes: wrong.length, sha256: "0".repeat(64) }),
    row({ asset_id: "monster.1007.spr", canonical_cp949_path: "data\\sprite\\몬스터\\fabre.spr", bytes: 999 }),
    row({ asset_id: "bgm.prt_fild08", canonical_cp949_path: "BGM\\12.mp3", bytes: bgm.length, source_container: "filesystem:BGM" }),
  ];
  const grfBytes = writeGrf([
    { rawName: hexToBytes(rows[0]?.raw_name_hex ?? ""), data: poring },
    { rawName: hexToBytes(rows[1]?.raw_name_hex ?? ""), data: gat },
    { rawName: hexToBytes(rows[2]?.raw_name_hex ?? ""), data: wrong },
    { rawName: hexToBytes(rows[3]?.raw_name_hex ?? ""), data: syntheticBytes(5, 10) },
  ]);
  const rdata = writeGrf([{ rawName: encodeCp949("data\\empty"), data: syntheticBytes(6, 3) }]);
  writeFileSync(join(d.root, "data.grf"), grfBytes);
  writeFileSync(join(d.root, "rdata.grf"), rdata);
  mkdirSync(join(d.root, "BGM"));
  writeFileSync(join(d.root, "BGM/12.mp3"), bgm);
  const derived = join(d.root, "derived");
  mkdirSync(derived);
  writeFileSync(join(derived, "monster.1002.spr.json"), JSON.stringify({ frames: 3 }));
  const lock: SourceLockLocal = {
    schemaVersion: 1, lockId: "synthetic", scannedAt: "2026-11-17T00:00:00Z", pathEncoding: "cp949", tool: "test",
    sources: {
      "data.grf": { path: join(d.root, "data.grf"), bytes: grfBytes.length, sha256: sha(grfBytes) },
      "rdata.grf": { path: join(d.root, "rdata.grf"), bytes: rdata.length, sha256: sha(rdata) },
      bgm: { path: join(d.root, "BGM"), fileCount: 1, manifestSha256: "B".repeat(64), files: [{ name: "12.mp3", bytes: bgm.length, sha256: sha(bgm) }] },
    },
  };
  const whitelist = new AssetWhitelist(rows);
  const gw = await startGateway({ config: { host: "127.0.0.1", port: 0, lanProfile: null }, whitelist, lock, buildId: "test-build", derivedDir: derived });
  cleanups.push(() => gw.close());
  return { gw, whitelist, data: { poring, gat, bgm }, lock };
}

function rawGet(url: string, headers: Record<string, string>, method = "GET"): Promise<number> {
  return new Promise((resolve, reject) => {
    const req = request(url, { method, headers }, (res) => {
      res.resume();
      resolve(res.statusCode ?? 0);
    });
    req.on("error", reject);
    req.end();
  });
}

describe("asset gateway + HttpAssetGatewayClient (synthetic GRF)", () => {
  it("health reports fan-local mode, build ID and locked source hashes", async () => {
    const { gw, whitelist, lock } = await fixture();
    const client = new HttpAssetGatewayClient({ baseUrl: gw.url, whitelist });
    const h = await client.health();
    expect(h).toEqual({ ok: true, mode: "fan-local", buildId: "test-build", sourceHashes: { "data.grf": lock.sources["data.grf"].sha256, "rdata.grf": lock.sources["rdata.grf"].sha256, bgm: "B".repeat(64) } });
  });

  it("serves whitelisted entries by raw CP949 hex with source hash headers", async () => {
    const { gw, whitelist, data } = await fixture();
    const client = new HttpAssetGatewayClient({ baseUrl: gw.url, whitelist });
    expect(new Uint8Array(await client.getBinary("monster.1002.spr"))).toEqual(data.poring);
    expect(new Uint8Array(await client.getBinary("map.prt_fild08.gat"))).toEqual(data.gat);
    expect(new Uint8Array(await client.getBinary("bgm.prt_fild08"))).toEqual(data.bgm);
    await expect(client.getJson("monster.1002.spr")).resolves.toEqual({ frames: 3 });
    await expect(client.resolvePath("monster.1002.spr")).resolves.toBe("fan-local://data.grf/x");
  });

  it("refuses size and SHA-256 mismatches against the whitelist", async () => {
    const { gw, whitelist } = await fixture();
    const client = new HttpAssetGatewayClient({ baseUrl: gw.url, whitelist });
    await expect(client.getBinary("map.prt_fild08.gnd")).rejects.toMatchObject({ code: "http-409" });
    await expect(client.getBinary("monster.1007.spr")).rejects.toMatchObject({ code: "http-409" });
  });

  it("rejects unknown IDs before any HTTP request", async () => {
    const { gw, whitelist } = await fixture();
    let calls = 0;
    const client = new HttpAssetGatewayClient({ baseUrl: gw.url, whitelist, fetch: (u, i) => { calls += 1; return fetch(u, i); } });
    await expect(client.getBinary("monster.9999.spr")).rejects.toBeInstanceOf(UnknownAssetError);
    await expect(client.getJson("../../etc/passwd")).rejects.toBeInstanceOf(UnknownAssetError);
    expect(calls).toBe(0);
  });

  it("server rejects paths, traversal, other methods, foreign Host and Origin headers", async () => {
    const { gw } = await fixture();
    expect(await rawGet(`${gw.url}/v1/assets/..%2F..%2Fdata.grf`, {})).toBe(404);
    expect(await rawGet(`${gw.url}/data/sprite/x.spr`, {})).toBe(404);
    expect(await rawGet(`${gw.url}/v1/assets/monster.9999.spr`, {})).toBe(404);
    expect(await rawGet(`${gw.url}/v1/derived/monster.1002.spr.json/../x`, {})).toBe(404);
    expect(await rawGet(`${gw.url}/health`, {}, "POST")).toBe(405);
    expect(await rawGet(`${gw.url}/health`, { host: "evil.example" })).toBe(421);
    expect(await rawGet(`${gw.url}/health`, { origin: "https://evil.example" })).toBe(403);
    expect(await rawGet(`${gw.url}/health`, { origin: "http://127.0.0.1:5173" })).toBe(200);
  });

  it("client enforces loopback, byte limits, content type and timeouts", async () => {
    const { whitelist } = await fixture();
    expect(() => new HttpAssetGatewayClient({ baseUrl: "http://192.168.1.10:4178", whitelist })).toThrow(GatewayError);
    expect(() => new HttpAssetGatewayClient({ baseUrl: "https://127.0.0.1:4178", whitelist })).toThrow(/http/u);
    expect(() => new HttpAssetGatewayClient({ baseUrl: "http://203.0.113.5:4178", whitelist, allowLan: true })).toThrow(/not loopback/u);
    expect(new HttpAssetGatewayClient({ baseUrl: "http://192.168.1.10:4178", whitelist, allowLan: true }).mode()).toBe("fan-local");

    const health = { ok: true, mode: "fan-local", buildId: "b", sourceHashes: { "data.grf": "A".repeat(64), "rdata.grf": null, bgm: null } };
    const fake = (body: Uint8Array, headers: Record<string, string>) => (u: string) =>
      Promise.resolve(u.endsWith("/health") ? new Response(JSON.stringify(health), { headers: { "content-type": "application/json" } }) : new Response(body, { headers }));
    const big = new HttpAssetGatewayClient({ baseUrl: "http://127.0.0.1:1", whitelist, fetch: fake(new Uint8Array(5000), { "content-type": "application/octet-stream", "x-ro-source-sha256": "A".repeat(64) }) });
    await expect(big.getBinary("monster.1002.spr")).rejects.toMatchObject({ code: "too-large" });
    const html = new HttpAssetGatewayClient({ baseUrl: "http://127.0.0.1:1", whitelist, fetch: fake(new Uint8Array(4321), { "content-type": "text/html" }) });
    await expect(html.getBinary("monster.1002.spr")).rejects.toMatchObject({ code: "bad-content-type" });
    const nosrc = new HttpAssetGatewayClient({ baseUrl: "http://127.0.0.1:1", whitelist, fetch: fake(new Uint8Array(4321), { "content-type": "application/octet-stream" }) });
    await expect(nosrc.getBinary("monster.1002.spr")).rejects.toMatchObject({ code: "no-source-hash" });
    const wrongsrc = new HttpAssetGatewayClient({ baseUrl: "http://127.0.0.1:1", whitelist, fetch: fake(new Uint8Array(4321), { "content-type": "application/octet-stream", "x-ro-source-sha256": "C".repeat(64) }) });
    await expect(wrongsrc.getBinary("monster.1002.spr")).rejects.toMatchObject({ code: "source-mismatch" });
    const hang = new HttpAssetGatewayClient({ baseUrl: "http://127.0.0.1:1", whitelist, timeoutMs: 50, fetch: (_u, init) => new Promise((_r, rej) => init?.signal?.addEventListener("abort", () => rej(new DOMException("aborted", "AbortError")))) });
    await expect(hang.health()).rejects.toMatchObject({ code: "timeout" });
  });

  it("connectAssetGateway falls back to the placeholder with a reason when offline", async () => {
    const { whitelist, gw } = await fixture();
    const online = await connectAssetGateway({ baseUrl: gw.url, whitelist, buildId: "x" });
    expect(online.mode()).toBe("fan-local");
    const offline = await connectAssetGateway({ baseUrl: "http://127.0.0.1:9", whitelist, buildId: "x", timeoutMs: 500 });
    expect(offline.mode()).toBe("placeholder");
    expect(offline.reason).toMatch(/未連線/u);
    expect(isPlaceholderBinary(await offline.getBinary("monster.1002.spr"))).toBe(true);
  });
});
